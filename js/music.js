function onPlayerStateChange(event) {
  const playBtn = document.getElementById("play-btn");

  if (event.data === YT.PlayerState.PLAYING) {
    isPlaying = true;
    playBtn.innerHTML = pauseSVG;
    vinylRecord.classList.add("spin");

    updateTrackInfoUI();
    updatePlaylistHighlight();

    clearInterval(progressInterval);
    progressInterval = setInterval(updateProgressBar, 1000);
  } else if (event.data === YT.PlayerState.PAUSED) {
    isPlaying = false;
    playBtn.innerHTML = playSVG;
    vinylRecord.classList.remove("spin");

    clearInterval(progressInterval);
    document.title = "Music - Yellow Taxi";
  } else if (event.data === YT.PlayerState.ENDED) {
    isPlaying = false;
    clearInterval(progressInterval);

    if (isRepeatOne) {
      player.seekTo(0);
      player.playVideo();
    } else {
      playNextTrack();
    }
  }
}

const progressBar = document.getElementById("progress-bar");
const progressFill = document.getElementById("progress-fill");
const currentTimeText = document.getElementById("current-time");
const totalTimeText = document.getElementById("total-time");
let isDragging = false;

function handleSeekInteraction(e) {
  if (!isPlayerReady || !player) return;
  const rect = progressBar.getBoundingClientRect();
  const clientX = e.touches ? e.touches[0].clientX : e.clientX;
  let clickX = clientX - rect.left;
  clickX = Math.max(0, Math.min(clickX, rect.width));

  const widthPercentage = rect.width > 0 ? clickX / rect.width : 0;
  progressFill.style.width = widthPercentage * 100 + "%";

  const duration = player.getDuration();
  if (duration > 0) {
    const seekTime = widthPercentage * duration;
    currentTimeText.textContent = formatTime(seekTime);
    totalTimeText.textContent = formatTime(duration);
  }
}

const startDragging = (e) => {
  isDragging = true;
  progressBar.classList.add("is-dragging");
  handleSeekInteraction(e);
};

const whileDragging = (e) => {
  if (isDragging) {
    if (e.type === "touchmove") e.preventDefault();
    handleSeekInteraction(e);
  }
};

const stopDragging = (e) => {
  if (isDragging) {
    isDragging = false;
    progressBar.classList.remove("is-dragging");
    const currentWidth = parseFloat(progressFill.style.width) / 100;
    if (
      player &&
      typeof player.seekTo === "function" &&
      player.getDuration() > 0
    ) {
      player.seekTo(currentWidth * player.getDuration(), true);
    }
  }
};

progressBar.addEventListener("mousedown", startDragging);
document.addEventListener("mousemove", whileDragging);
document.addEventListener("mouseup", stopDragging);

progressBar.addEventListener("touchstart", startDragging, { passive: false });
document.addEventListener("touchmove", whileDragging, { passive: false });
document.addEventListener("touchend", stopDragging);

function updateProgressBar() {
  if (!player || !isPlaying || isDragging) return;
  const currentTime = player.getCurrentTime();
  const duration = player.getDuration();

  if (duration > 0) {
    document.getElementById("progress-fill").style.width =
      (currentTime / duration) * 100 + "%";
    currentTimeText.textContent = formatTime(currentTime);
    totalTimeText.textContent = formatTime(duration);
  }
}

function formatTime(seconds) {
  if (!seconds) return "0:00";
  const min = Math.floor(seconds / 60);
  const sec = Math.floor(seconds % 60);
  return min + ":" + (sec < 10 ? "0" + sec : sec);
}

document.addEventListener("keydown", function (event) {
  if (
    event.target.tagName === "INPUT" ||
    event.target.tagName === "TEXTAREA" ||
    event.target.isContentEditable
  )
    return;

  switch (event.code) {
    case "Space":
    case "MediaPlayPause":
      event.preventDefault();
      if (isPlayerReady && player) {
        if (isPlaying) player.pauseVideo();
        else player.playVideo();
      }
      break;
    case "ArrowRight":
    case "MediaTrackNext":
      document.getElementById("next-btn").click();
      break;
    case "ArrowLeft":
    case "MediaTrackPrevious":
      document.getElementById("prev-btn").click();
      break;
    case "ArrowUp":
      event.preventDefault();
      if (isPlayerReady && player && typeof player.getVolume === "function") {
        let currentVol = player.getVolume();
        player.setVolume(Math.min(currentVol + 10, 100));
      }
      break;
    case "ArrowDown":
      event.preventDefault();
      if (isPlayerReady && player && typeof player.getVolume === "function") {
        let currentVol = player.getVolume();
        player.setVolume(Math.max(currentVol - 10, 0));
      }
      break;
  }
});
