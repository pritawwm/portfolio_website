const originalTrackIds = Object.keys(customTrackInfo);
let currentTrackIds = [...originalTrackIds];
let currentIndex = 0;

let player;
let isPlaying = false;
let isShuffle = false;
let isRepeatOne = false;
let progressInterval;
let isPlayerReady = false;

const tag = document.createElement("script");
tag.src = "https://www.youtube.com/iframe_api";
const firstScriptTag = document.getElementsByTagName("script")[0];
firstScriptTag.parentNode.insertBefore(tag, firstScriptTag);

function onYouTubeIframeAPIReady() {
  player = new YT.Player("hidden-player", {
    height: "200",
    width: "200",
    videoId: currentTrackIds[currentIndex],
    playerVars: {
      playsinline: 1,
      autoplay: 0,
      origin: window.location.origin,
    },
    events: {
      onReady: onPlayerReady,
      onStateChange: onPlayerStateChange,
      onError: onPlayerError,
    },
  });
}

function onPlayerReady(event) {
  isPlayerReady = true;
  renderPlaylist();
  updateTrackInfoUI();
}

function onPlayerError(event) {
  if (event.data === 150 || event.data === 101 || event.data === 100) {
    document.getElementById("track-name").textContent =
      "Song blocked. Skipping...";
    setTimeout(playNextTrack, 1500);
  }
}

function loadTrack(index) {
  if (!isPlayerReady || !player) return;
  currentIndex = index;
  const vidId = currentTrackIds[currentIndex];

  player.loadVideoById(vidId);

  updateTrackInfoUI();
  updatePlaylistHighlight();
}

function playNextTrack() {
  if (currentIndex < currentTrackIds.length - 1) {
    currentIndex++;
  } else {
    currentIndex = 0;
  }
  loadTrack(currentIndex);
}

function playPrevTrack() {
  if (currentIndex > 0) {
    currentIndex--;
  } else {
    currentIndex = currentTrackIds.length - 1;
  }
  loadTrack(currentIndex);
}

function updateTrackInfoUI() {
  const vidId = currentTrackIds[currentIndex];
  const info = customTrackInfo[vidId] || {
    title: "Unknown Track",
    artist: "Unknown Artist",
  };

  document.getElementById("track-name").textContent = info.title;
  document.getElementById("artist-name").textContent = info.artist;

  if (isPlaying) {
    document.title = `${info.title} - Yellow Taxi`;
  }
}

function renderPlaylist() {
  const ul = document.getElementById("playlist-list");
  ul.innerHTML = "";

  currentTrackIds.forEach((vidId, index) => {
    let info = customTrackInfo[vidId] || {
      title: "Unknown Track",
      artist: "Unknown Artist",
    };
    let li = document.createElement("li");
    li.className = "playlist-item";
    li.dataset.vid = vidId;
    li.innerHTML = `
                <span class="pl-index">${index + 1}</span>
                <span class="pl-title">${info.title}</span>
                <span class="pl-artist">${info.artist}</span>
            `;
    li.onclick = () => {
      loadTrack(index);
      document.getElementById("playlist-overlay").classList.remove("active");
      document.getElementById("playlist-btn").classList.remove("active");
    };
    ul.appendChild(li);
  });

  updatePlaylistHighlight();
}

function updatePlaylistHighlight() {
  if (!currentTrackIds.length) return;

  const currentVidId = currentTrackIds[currentIndex];
  const items = document.querySelectorAll(".playlist-item");
  items.forEach((item) => item.classList.remove("playing-track"));

  const activeItem = document.querySelector(
    `.playlist-item[data-vid="${currentVidId}"]`,
  );
  if (activeItem) {
    activeItem.classList.add("playing-track");

    setTimeout(() => {
      activeItem.scrollIntoView({ behavior: "smooth", block: "nearest" });
    }, 50);
  }
}

document.getElementById("shuffle-btn").addEventListener("click", () => {
  isShuffle = !isShuffle;
  const btn = document.getElementById("shuffle-btn");
  const currentVidId = currentTrackIds[currentIndex];

  if (isShuffle) {
    btn.classList.add("active");
    let tempArray = [...originalTrackIds].filter((id) => id !== currentVidId);

    for (let i = tempArray.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [tempArray[i], tempArray[j]] = [tempArray[j], tempArray[i]];
    }

    currentTrackIds = [currentVidId, ...tempArray];
    currentIndex = 0;
  } else {
    btn.classList.remove("active");
    currentTrackIds = [...originalTrackIds];
    currentIndex = currentTrackIds.indexOf(currentVidId);
  }

  renderPlaylist();
});

document.getElementById("playlist-btn").addEventListener("click", () => {
  document.getElementById("playlist-overlay").classList.toggle("active");
  document.getElementById("playlist-btn").classList.toggle("active");

  if (
    document.getElementById("playlist-overlay").classList.contains("active")
  ) {
    updatePlaylistHighlight();
  }
});

